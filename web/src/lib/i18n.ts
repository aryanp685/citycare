/** Returns missing or empty catalog paths, so incomplete locales can be gated explicitly. */
export function missingMessages(locale: Locale): string[] {
  return NAMESPACES.flatMap((ns) => Object.keys(en[ns]).filter((key) => {
    const value = (CATALOGS[locale][ns] as Record<string, string | undefined>)[key];
    return typeof value !== "string" || !value.trim();
  }).map((key) => `${ns}.${key}`));
}

/** Missing translations fall back to English; development warns and unknown keys throw. */
export function translate<N extends Namespace>(locale: Locale, namespace: N, key: MessageKey<N>): string {
  const source = (en[namespace] as Record<string, string>)[key];
  if (!source) throw new Error(`Unknown translation key: ${namespace}.${key}`);
  const value = (CATALOGS[locale][namespace] as Record<string, string | undefined>)[key];
  if (value && value.trim()) return value;
  if (process.env.NODE_ENV !== "production") console.warn(`Missing translation: ${locale}.${namespace}.${key}`);
  return source;
}
