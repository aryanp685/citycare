export const DEFAULT_LOCALE: Locale = "en";
export function resolveLocale(raw: unknown): Locale {
  return typeof raw === "string" && (LOCALES as readonly string[]).includes(raw) ? raw as Locale : DEFAULT_LOCALE;
}

